 local near=buckets[key(x,y,z)] or {} local exact=false local shapeFound=false local notes={}
 for _,part in ipairs(near) do
  local size=part.Size
  local shape=math.abs(size.X-sx)<.05 and math.abs(size.Y-sy)<.05 and math.abs(size.Z-sz)<.05
  local props=part.Material.Name==material and colorHex(part.Color)==hex and part.CanCollide==collide and part.Anchored
  if shape then shapeFound=true end
  if shape and props then exact=true break end
  if #notes<3 then notes[#notes+1]=string.format("size=%.1f,%.1f,%.1f color=%s material=%s collide=%s owner=%s",size.X,size.Y,size.Z,colorHex(part.Color),part.Material.Name,tostring(part.CanCollide),part.Parent and part.Parent.Name or "?") end
 end
 if shapeFound then present+=1 end
 if exact then matched+=1 else
  local line=string.format("#%d @ %.1f,%.1f,%.1f size %.1f,%.1f,%.1f %s %s; nearby: %s",id,x,y,z,sx,sy,sz,hex,material,#notes>0 and table.concat(notes," | ") or "none")
  if shapeFound then wrong[#wrong+1]=line else missing[#missing+1]=line end
 end
end
local header=string.format("SEED30 FLOOR5: exact %d/546; geometry present %d/546; missing %d; wrong properties %d; world bricks %d",matched,present,#missing,#wrong,#parts)
print(header)
for _,line in ipairs(missing) do print("MISSING",line) end
for i=1,math.min(#wrong,20) do print("WRONG",wrong[i]) end
local report=header.."\n"..table.concat(missing,"\n").."\n"..table.concat(wrong,"\n")
if setclipboard then pcall(setclipboard,report) print("SEED30: diagnostic copied to clipboard") end
